/** Polish plural: 1 dzień, 2–4 dni, 5+ dni (with 12–14 exception). */
function pl(n: number, one: string, few: string, many: string) {
  if (n === 1) return one
  const d = n % 10
  const dd = n % 100
  return d >= 2 && d <= 4 && (dd < 12 || dd > 14) ? few : many
}

